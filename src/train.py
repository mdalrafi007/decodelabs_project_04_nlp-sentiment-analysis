"""Train, tune, evaluate and save the sentiment models.

Run from the project root:  python -m src.train
"""
from __future__ import annotations

import argparse
import json
import platform
import shutil
import sys
from pathlib import Path
from typing import Optional

import joblib
import numpy as np
import pandas as pd
from sklearn.model_selection import GridSearchCV, StratifiedKFold, train_test_split

from .data_loader import (PROJECT_ROOT, DatasetUnavailableError, clean_reviews,
                          download_dataset, load_reviews)
from .eda import run_eda
from .evaluate import (compute_metrics, error_table, plot_confusion_matrix,
                       plot_model_comparison, top_features)
from .model import DISPLAY_NAMES, MODEL_NAMES, PARAM_GRIDS, SEED, build_pipeline
from .preprocessing import ensure_nltk_resources

FIG_DIR = PROJECT_ROOT / "reports" / "figures"
RESULTS_DIR = PROJECT_ROOT / "reports" / "results"
MODEL_DIR = PROJECT_ROOT / "models"
CACHE_DIR = PROJECT_ROOT / ".cache"
MODEL_PATH = MODEL_DIR / "sentiment_model.joblib"


def _fmt(x: float) -> str:
    return f"{x:.4f}"


def write_results_md(summary: dict, path: Path) -> None:
    """Generate a human-readable results file from the real run only."""
    lines = ["# Results (generated by `python -m src.train`)", ""]
    d = summary["data"]
    lines += [
        "## Data",
        f"- Rows loaded: {d['rows_loaded']}; after cleaning: {d['rows_after_cleaning']}",
        f"- Class counts (0=Negative, 1=Positive): {d['class_counts']}",
        f"- Train / test sizes: {summary['split']['train']} / {summary['split']['test']} "
        f"(stratified, seed {summary['seed']})",
        "",
        "## Cross-validation on the training split (model selection)",
        "| Model | Best CV F1 | Best parameters |",
        "|---|---|---|",
    ]
    for name in MODEL_NAMES:
        m = summary["models"][name]
        lines.append(f"| {DISPLAY_NAMES[name]} | {_fmt(m['cv_f1'])} | `{m['best_params']}` |")
    lines += ["", "## Held-out test results (positive class = Positive)",
              "| Model | Accuracy | Precision | Recall | F1 | ROC-AUC |", "|---|---|---|---|---|---|"]
    for name in MODEL_NAMES:
        t = summary["models"][name]["test"]
        lines.append(f"| {DISPLAY_NAMES[name]} | {_fmt(t['accuracy'])} | {_fmt(t['precision'])} | "
                     f"{_fmt(t['recall'])} | {_fmt(t['f1'])} | {_fmt(t['roc_auc'])} |")
    lines += ["", f"**Selected model:** {DISPLAY_NAMES[summary['selected_model']]} "
                  "(highest cross-validated F1 on the training split; the test set was not used to choose).",
              "", "## Confusion matrices (rows = actual Neg/Pos, columns = predicted Neg/Pos)"]
    for name in MODEL_NAMES:
        lines.append(f"- {DISPLAY_NAMES[name]}: `{summary['models'][name]['test']['confusion_matrix']}`")
    for name in MODEL_NAMES:
        lines += ["", f"## Classification report: {DISPLAY_NAMES[name]}", "```",
                  summary["models"][name]["test"]["classification_report"], "```"]
    lines += ["", "## Files", "- Figures: `reports/figures/`",
              "- Misclassified and sample correct reviews: `reports/results/errors.csv`",
              "- Influential features: `reports/results/top_features.csv`",
              "- Raw numbers: `reports/results/metrics.json`"]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def run_training(subset: str = "amazon", data_path: Optional[str] = None, seed: int = SEED,
                 test_size: float = 0.2, cv: int = 5, download: bool = True) -> dict:
    """Full workflow. Returns the summary dict that is also saved to disk."""
    ensure_nltk_resources()
    if data_path is None and download:
        download_dataset(["amazon", "imdb", "yelp"] if subset == "all" else [subset])
    raw, malformed = load_reviews(subset, Path(data_path) if data_path else None)
    df, data_report = clean_reviews(raw, malformed)
    for d in (FIG_DIR, RESULTS_DIR, MODEL_DIR):
        d.mkdir(parents=True, exist_ok=True)
    (PROJECT_ROOT / "data" / "processed").mkdir(parents=True, exist_ok=True)
    df.to_csv(PROJECT_ROOT / "data" / "processed" / "reviews_clean.csv", index=False)

    eda_stats = run_eda(df, FIG_DIR)

    X_train, X_test, y_train, y_test = train_test_split(
        df["text"].tolist(), df["label"].to_numpy(), test_size=test_size,
        stratify=df["label"], random_state=seed,
    )

    if CACHE_DIR.exists():
        shutil.rmtree(CACHE_DIR)  # stale cache would hide preprocessing changes
    splitter = StratifiedKFold(n_splits=cv, shuffle=True, random_state=seed)

    fitted, models_summary, metrics_for_plot = {}, {}, {}
    for name in MODEL_NAMES:
        print(f"[train] tuning {DISPLAY_NAMES[name]} with {cv}-fold CV on the training split ...")
        search = GridSearchCV(build_pipeline(name, seed, memory=str(CACHE_DIR)), PARAM_GRIDS[name],
                              cv=splitter, scoring="f1", n_jobs=1, refit=True)
        search.fit(X_train, y_train)  # TF-IDF is re-fitted inside every training fold
        best = search.best_estimator_
        best.set_params(memory=None)
        test_metrics = compute_metrics(best, X_test, y_test)
        fitted[name] = best
        metrics_for_plot[name] = test_metrics
        models_summary[name] = {
            "cv_f1": float(search.best_score_),
            "best_params": {k: (list(v) if isinstance(v, tuple) else v)
                            for k, v in search.best_params_.items()},
            "test": test_metrics,
        }
        plot_confusion_matrix(test_metrics["confusion_matrix"],
                              f"Confusion matrix: {DISPLAY_NAMES[name]}",
                              FIG_DIR / f"confusion_matrix_{name}.png")
    plot_model_comparison(metrics_for_plot, FIG_DIR / "model_comparison.png")

    selected = max(MODEL_NAMES, key=lambda n: models_summary[n]["cv_f1"])
    final = fitted[selected]
    joblib.dump(final, MODEL_PATH, compress=3)

    preds = final.predict(X_test)
    errors = error_table(X_test, y_test, preds)
    wrong = errors[~errors["correct"]]
    right = errors[errors["correct"]].sample(n=min(10, int(errors["correct"].sum())), random_state=seed)
    pd.concat([wrong, right]).to_csv(RESULTS_DIR / "errors.csv", index=False)
    top_features(final).to_csv(RESULTS_DIR / "top_features.csv", index=False)

    import nltk
    import sklearn
    summary = {
        "seed": seed,
        "data": data_report,
        "eda": eda_stats,
        "split": {"train": len(X_train), "test": len(X_test), "test_size": test_size},
        "models": models_summary,
        "selected_model": selected,
        "selection_rule": "highest mean cross-validated F1 on the training split",
        "environment": {
            "python": sys.version.split()[0], "platform": platform.platform(),
            "scikit_learn": sklearn.__version__, "nltk": nltk.__version__,
            "pandas": pd.__version__, "numpy": np.__version__,
        },
    }
    (RESULTS_DIR / "metrics.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    (MODEL_DIR / "model_metadata.json").write_text(json.dumps({
        "selected_model": selected, "best_params": models_summary[selected]["best_params"],
        "seed": seed, "environment": summary["environment"],
        "note": "Load only trusted .joblib files; pickles can break across library versions.",
    }, indent=2), encoding="utf-8")
    write_results_md(summary, RESULTS_DIR / "RESULTS.md")
    shutil.rmtree(CACHE_DIR, ignore_errors=True)
    return summary


def main() -> None:
    parser = argparse.ArgumentParser(description="Train sentiment models.")
    parser.add_argument("--subset", default="amazon", choices=["amazon", "imdb", "yelp", "all"])
    parser.add_argument("--data-path", default=None, help="Use a local 'text<TAB>label' file instead.")
    parser.add_argument("--seed", type=int, default=SEED)
    parser.add_argument("--test-size", type=float, default=0.2)
    parser.add_argument("--cv", type=int, default=5)
    parser.add_argument("--no-download", action="store_true", help="Do not try to download data.")
    args = parser.parse_args()
    try:
        summary = run_training(args.subset, args.data_path, args.seed, args.test_size,
                               args.cv, not args.no_download)
    except (DatasetUnavailableError, RuntimeError) as exc:
        sys.exit(f"ERROR: {exc}")
    print(f"\nSelected model: {DISPLAY_NAMES[summary['selected_model']]}")
    for name in MODEL_NAMES:
        t = summary["models"][name]["test"]
        print(f"  {DISPLAY_NAMES[name]:<26} acc={t['accuracy']:.3f} f1={t['f1']:.3f} auc={t['roc_auc']:.3f}")
    print(f"\nSaved model:   {MODEL_PATH}\nSaved results: {RESULTS_DIR / 'RESULTS.md'}")


if __name__ == "__main__":
    main()
